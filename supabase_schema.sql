-- 1. Users Table
CREATE TABLE IF NOT EXISTS public.users (
  email TEXT PRIMARY KEY,
  name TEXT NOT NULL,
  role TEXT NOT NULL CHECK (role IN ('it_admin', 'admin', 'operator')),
  locations JSONB,
  location TEXT,
  plant TEXT,
  line TEXT,
  lines JSONB
);

-- 2. SAP Mapping Table
CREATE TABLE IF NOT EXISTS public.sap_mapping (
  sap_code TEXT PRIMARY KEY,
  description TEXT NOT NULL
);

-- 3. SAP Remap Table
CREATE TABLE IF NOT EXISTS public.sap_remap (
  old_sap TEXT PRIMARY KEY REFERENCES public.sap_mapping(sap_code) ON DELETE CASCADE,
  new_sap TEXT NOT NULL REFERENCES public.sap_mapping(sap_code) ON DELETE CASCADE
);

-- 4. QR Logs Table
CREATE TABLE IF NOT EXISTS public.qr_logs (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  qr_code TEXT NOT NULL,
  new_qr_code TEXT,
  sap_code TEXT NOT NULL,
  old_sap_code TEXT,
  description TEXT NOT NULL,
  month TEXT NOT NULL,
  year TEXT NOT NULL,
  week TEXT NOT NULL,
  serial TEXT NOT NULL,
  plant TEXT NOT NULL,
  location TEXT NOT NULL,
  line TEXT NOT NULL,
  user_email TEXT NOT NULL,
  timestamp BIGINT NOT NULL,
  print_status TEXT DEFAULT 'pending' CHECK (print_status IN ('pending', 'success', 'failed'))
);

-- Performance Indexes
CREATE INDEX IF NOT EXISTS idx_qr_logs_timestamp ON public.qr_logs(timestamp DESC);
CREATE INDEX IF NOT EXISTS idx_qr_logs_plant_loc_line ON public.qr_logs(plant, location, line);
CREATE INDEX IF NOT EXISTS idx_qr_logs_user ON public.qr_logs(user_email);
CREATE INDEX IF NOT EXISTS idx_qr_logs_codes ON public.qr_logs(qr_code, new_qr_code, sap_code);

-- 5. QR Configuration Table
CREATE TABLE IF NOT EXISTS public.qr_config (
  id INT PRIMARY KEY,
  length INT NOT NULL DEFAULT 22,
  pattern TEXT NOT NULL DEFAULT 'numeric' CHECK (pattern IN ('numeric', 'alphanumeric')),
  "sequenceValidation" BOOLEAN NOT NULL DEFAULT FALSE,
  prefix TEXT DEFAULT '',
  suffix TEXT DEFAULT '',
  month_format TEXT DEFAULT 'MM',
  year_format TEXT DEFAULT 'YY',
  week_format TEXT DEFAULT 'WW',
  sap_length INT DEFAULT 10,
  auto_inc_length INT DEFAULT 6,
  config_password TEXT DEFAULT 'admin@pg123'
);

-- 6. Plant QR Configuration Table
CREATE TABLE IF NOT EXISTS public.qr_config_plant (
  location TEXT NOT NULL,
  plant TEXT NOT NULL,
  length INT NOT NULL DEFAULT 22,
  pattern TEXT NOT NULL DEFAULT 'numeric' CHECK (pattern IN ('numeric', 'alphanumeric')),
  "sequenceValidation" BOOLEAN NOT NULL DEFAULT FALSE,
  prefix TEXT DEFAULT '',
  suffix TEXT DEFAULT '',
  month_format TEXT DEFAULT 'MM',
  year_format TEXT DEFAULT 'YY',
  week_format TEXT DEFAULT 'WW',
  sap_length INT DEFAULT 10,
  auto_inc_length INT DEFAULT 6,
  PRIMARY KEY (location, plant)
);

-- 7. Hierarchy Table
CREATE TABLE IF NOT EXISTS public.hierarchy (
  id INT PRIMARY KEY,
  locations JSONB NOT NULL DEFAULT '[]'::jsonb,
  plants JSONB NOT NULL DEFAULT '{}'::jsonb,
  lines JSONB NOT NULL DEFAULT '{}'::jsonb
);

